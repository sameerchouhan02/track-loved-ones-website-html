            async function handleSendAadhaarOtp() {
                const aadhaarInput = document.getElementById('parentAadhaar');
                const aadhaarVal = aadhaarInput ? aadhaarInput.value.replace(/[^0-9]/g, '') : '';
                if (!aadhaarVal || aadhaarVal.length !== 12) {
                    showToast('Kripya pehle 12-digit Parent Aadhaar Number daalein.', 'error');
                    if (aadhaarInput) aadhaarInput.focus();
                    return;
                }

                const btn = document.getElementById('btnSendAadhaarOtp');
                if (btn) {
                    btn.disabled = true;
                    btn.innerText = 'Sending...';
                }

                try {
                    const phoneInput = document.getElementById('parentPhone');
                    const phone = phoneInput ? phoneInput.value.trim().replace(/[^0-9]/g, '') : '';

                    const response = await fetch(`${LIVEURL}/auth/send-parent-consent-otp`, {
                        method: 'POST',
                        headers: { 'Content-Type': 'application/json' },
                        body: JSON.stringify({ token: window.__CONSENT_CODE__, phone: phone || undefined, aadhaarNumber: aadhaarVal })
                    });
                    const data = await response.json();
                    if (!response.ok || !data.success) {
                        throw new Error(data.message || 'Aadhaar OTP request failed.');
                    }

                    showToast(data.message || 'Aadhaar OTP aapke registered mobile par bhej diya gaya hai.', 'success');
                } catch (error) {
                    console.warn(error.message || 'Aadhaar OTP request failed.');
                    showToast(error.message || 'Aadhaar OTP bhejne mein samasya hui.', 'error');
                    if (btn) {
                        btn.disabled = false;
                        btn.innerText = 'Send Aadhaar OTP';
                    }
                    return;
                }
                const aadhaarOtpSec = document.getElementById('aadhaarOtpSection');
                if (aadhaarOtpSec) aadhaarOtpSec.style.display = 'flex';
                if (btn) btn.innerText = 'OTP Sent';
                isAadhaarOtpSent = true;
                startAadhaarResendTimer();
                updateButtonState();
                setTimeout(() => {
                    const aOtpInput = document.getElementById('aadhaarOtpInput');
                    if (aOtpInput) aOtpInput.focus();
                }, 150);
            }

            // OTP Sending does NOT block on checkboxes. Phone number verification happens first!
            async function handleSendOtp() {
                const phoneInput = document.getElementById('parentPhone');
                const phone = phoneInput ? phoneInput.value.trim().replace(/[^0-9]/g, '') : '';
                if (!phone || phone.length < 10) {
                    showToast('Kripya valid 10-digit Indian Mobile Number daalein.', 'error');
                    if (phoneInput) phoneInput.focus();
                    return;
                }

                const btn = document.getElementById('btnSendOtp');
                btn.disabled = true;
                btn.innerText = 'Sending...';

                try {
                    const res = await fetch(`${LIVEURL}/auth/send-parent-consent-otp`, {
                        method: 'POST',
                        headers: { 'Content-Type': 'application/json' },
                        body: JSON.stringify({ token: window.__CONSENT_CODE__, phone: phone })
                    });
                    const data = await res.json();
                    if (data.success) {
                        showToast(data.message || 'OTP aapke mobile number par bhej diya gaya hai.', 'success');
                        document.getElementById('otpSection').style.display = 'flex';
                        phoneInput.disabled = true;
                        btn.innerText = 'OTP Sent';
                        isOtpSent = true;
                        startResendTimer();
                        updateButtonState();
                        setTimeout(() => {
                            const otpInput = document.getElementById('otpInput');
                            if (otpInput) otpInput.focus();
                        }, 150);
                    } else {
                        showToast(data.message || 'OTP bhejne me dikkat aayi.', 'error');
                        btn.disabled = false;
                        btn.innerText = 'SEND OTP';
                    }
                } catch (e) {
                    showToast('Network error. Kripya dobara koshish karein.', 'error');
                    btn.disabled = false;
                    btn.innerText = 'SEND OTP';
                }
            }

