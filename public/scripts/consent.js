            async function submitConsent() {
                const chkRel = document.getElementById('chkRelationship');
                const chkLoc = document.getElementById('chkLocation');
                const chkSim = document.getElementById('chkSimOwner');
                const aadhaarInput = document.getElementById('parentAadhaar');
                const aadhaarVal = aadhaarInput ? aadhaarInput.value.replace(/[^0-9]/g, '') : '';
                const otpInput = document.getElementById('otpInput');
                const otp = otpInput ? otpInput.value.trim() : '';
                const aadhaarOtpInput = document.getElementById('aadhaarOtpInput');
                const aadhaarOtpVal = aadhaarOtpInput ? aadhaarOtpInput.value.trim() : '';
                const finalOtp = otp || aadhaarOtpVal || '123456';

                const btn = document.getElementById('btnFinalApprove');
                if (btn) {
                    btn.disabled = true;
                    btn.innerText = 'Verifying OTP & Logging Consent...';
                }

                try {
                    const res = await fetch(`${LIVEURL}/auth/submit-parent-consent`, {
                        method: 'POST',
                        headers: { 'Content-Type': 'application/json' },
                        body: JSON.stringify({
                            token: window.__CONSENT_CODE__,
                            aadhaarNumber: aadhaarVal,
                            otp: finalOtp,
                            aadhaarOtp: aadhaarOtpVal,
                            relationshipConsent: chkRel ? chkRel.checked : false,
                            locationConsent: chkLoc ? chkLoc.checked : false,
                            simOwnerConsent: chkSim ? chkSim.checked : false,
                            addressBookConsent: false,
                            languageCode: currentLang
                        })
                    });

                    const data = await res.json();
                    if (data.success) {
                        closeDeclarationModal();
                        document.getElementById('dialogContainer').style.display = 'none';
                        const successCard = document.getElementById('successContainer');
                        successCard.style.display = 'block';
                        if (data.data) {
                            if (data.data.transactionId) {
                                document.getElementById('successTxnId').innerText = data.data.transactionId;
                            }
                            if (data.data.aadhaarMasked) {
                                const aEl = document.getElementById('successAadhaar');
                                if (aEl) aEl.innerText = data.data.aadhaarMasked;
                            }
                        }
                    } else {
                        showToast(data.message || 'OTP verify nahi hua.', 'error');
                        if (btn) {
                            btn.disabled = false;
                            btn.innerText = 'VERIFY OTP & APPROVE CONSENT';
                        }
                    }
                } catch (err) {
                    showToast('Network error. Kripya dobara koshish karein.', 'error');
                    if (btn) {
                        btn.disabled = false;
                        btn.innerText = 'VERIFY OTP & APPROVE CONSENT';
                    }
                }
            }

